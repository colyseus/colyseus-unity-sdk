		[Test]
		public void InputEncoderReliableTest()
		{
			var input = new SchemaTest.Input.MoveInput();
			var encoder = new InputEncoder(input);

			input.vx = 1.5f; input.vy = -2; input.jump = true; input.action = 3;
			CollectionAssert.AreEqual(new byte[] { 128, 202, 0, 0, 192, 63, 129, 254, 130, 1, 131, 3 }, encoder.Encode());

			input.vx = 2.5f;
			CollectionAssert.AreEqual(new byte[] { 128, 202, 0, 0, 32, 64 }, encoder.Encode());

