		[Test]
		public void HandleAckRttTest()
		{
			double now = 0;
			var originalNow = RoomClock.GetNow;
			RoomClock.GetNow = () => now;

			try
			{
				var (handle, stub, input) = MakeHandle(new StubClock());

				now = 1000; input.vx = 1; handle.Send();
				now = 1016; input.vx = 2; handle.Send();
				now = 1033; input.vx = 3; handle.Send();

				now = 1080;
				Assert.AreEqual(80, handle.AckInput(1));
				Assert.AreEqual(-1, handle.AckInput(1)); // stale
				now = 1120;
				Assert.AreEqual(87, handle.AckInput(3)); // skips 2
				Assert.AreEqual(3, handle.LastProcessed);
				Assert.AreEqual(0, handle.PendingCount);

				// replay ring: pending inputs readable until acked
				now = 1200; input.vx = 4; handle.Send(); // seq 4
				Assert.AreEqual(4f, ((SchemaTest.Input.MoveInput)handle.At(4)).vx);
				Assert.IsNull(handle.At(3));             // acked → gone

				// reset: epoch++, fresh counters, next send = full snapshot
				int epochBefore = handle.Epoch;
				handle.Reset();
				Assert.AreEqual(epochBefore + 1, handle.Epoch);
				Assert.AreEqual(0, handle.SentCount);
				now = 1300; input.vx = 5;
				Assert.AreEqual(1, handle.Send());
				CollectionAssert.AreEqual(new byte[] { 19, 128, 5, 129, 0, 130, 0, 131, 0 }, stub.Sent[stub.Sent.Count - 1]);
				now = 1360;
				Assert.AreEqual(60, handle.AckInput(1));
			}
			finally
			{
				RoomClock.GetNow = originalNow;
			}
		}

		[Test]
		public void RoomClockSamplesTest()
		{
			double now = 0;
			var originalNow = RoomClock.GetNow;
			RoomClock.GetNow = () => now;

			try
			{
				var clock = new RoomClock();
				clock.SetPatchInterval(50);

				// (tNow, sNow, rtt) → (offset, rtt, smoothedRtt, jitter, lastServerTime)
				var script = new[]
				{
					new double[] { 1000, 500, -1,    -500, 0, 0, 0, 500 },
					new double[] { 1050, 550, 80,    -496, 80, 80, 0, 550 },
					new double[] { 1100, 600, 84,    -492.20000000000005, 84, 80.4, 0, 600 },
					new double[] { 1155, 655, 90,    -488.4800000000001, 90, 81.36000000000001, 0.3125, 655 },
					new double[] { 1205, 705, 76,    -485.83200000000005, 76, 80.82400000000001, 0.29296875, 705 },
					new double[] { 1305, 805, 82,    -483.14880000000005, 82, 80.94160000000002, 0.274658203125, 805 },
					new double[] { 1655, 1155, 78,   -480.93392000000006, 78, 80.64744000000002, 0.274658203125, 1155 },
					new double[] { 1705, 1205, 400,  -480.93392000000006, 78, 80.64744000000002, 0.2574920654296875, 1205 },
					new double[] { 1755, 1255, 74,   -479.1405280000001, 74, 79.98269600000002, 0.24139881134033203, 1255 },
				};
				foreach (var row in script)
				{
					now = row[0];
					clock.Sample(row[1], row[2]);
					Assert.AreEqual(row[3], clock._clockOffset);
					Assert.AreEqual(row[4], clock.Rtt());
					Assert.AreEqual(row[5], clock.SmoothedRtt());
					Assert.AreEqual(row[6], clock.Jitter());
					Assert.AreEqual(row[7], clock.LastServerTime());
				}

				now = 1800;
				Assert.AreEqual(1320.8594719999999, clock.ServerNow());

				// RenderNow — 1e-6 tolerance (exp() ULP variance across libms)
				now = 1800;
				double r1 = clock.RenderNow();
				now = 1816;
				double r2 = clock.RenderNow();
				now = 1816.2;
				double r3 = clock.RenderNow(); // same frame → unchanged
				Assert.AreEqual(1320.8594719999999, r1, 1e-6);
				Assert.AreEqual(1336.8594719999999, r2, 1e-6);
				Assert.AreEqual(r2, r3);

				// reset clears estimates; patch interval is config and survives
				clock.Reset();
				Assert.AreEqual(0, clock.SmoothedRtt());
				Assert.AreEqual(0, clock.LastServerTime());
				Assert.AreEqual(50, clock.PatchInterval());
			}
			finally
			{
				RoomClock.GetNow = originalNow;
			}
		}

