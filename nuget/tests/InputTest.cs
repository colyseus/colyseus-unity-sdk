		[Test]
		public void RoomClockGateWarmupTest()
		{
			double now = 0;
			var originalNow = RoomClock.GetNow;
			RoomClock.GetNow = () => now;

			try
			{
				var clock = new RoomClock();
				clock.SetPatchInterval(50);
				double tNow = 1000;
				var expected = new Dictionary<int, double[]>
				{
					[5]  = new double[] { -341.855, 116.29 },
					[10] = new double[] { -332.85995895, 134.28008210000002 },
					[15] = new[] { -331.7339771603856, 136.53204567922904 },
					[20] = new[] { -326.88359617343616, 146.23280765312796 },
					[25] = new[] { -328.20499470445236, 143.59001059109553 },
					[30] = new[] { -324.79976732303214, 150.40046535393603 },
					[35] = new[] { -331.6290303784904, 146.0509707868457 },
				};
				for (int i = 1; i <= 35; i++)
				{
					tNow += 50;
					now = tNow;
					double rtt = i % 2 == 0 ? 200 : 100;
					clock.Sample(tNow - 400, rtt);
					if (expected.TryGetValue(i, out var want))
					{
						Assert.AreEqual(want[0], clock._clockOffset);
						Assert.AreEqual(want[1], clock.SmoothedRtt());
					}
				}
			}
			finally
			{
				RoomClock.GetNow = originalNow;
			}
		}
