			);
		}
		public static Exception SerializingSpecialSystemType(Type type)
		{
			return new JsonSerializationException
			(
				string.Format("Attempt to serialize special system type '{0}' failed. This type is restricted and cannot be serialized. This typically occurs when using low-level types like 'Pointer', 'RuntimeHandle', or 'IntPtr' in your data contract.", type.FullName),
				ErrorCode.SerializingSpecialSystemType
			);
		}
		public static Exception UnexpectedEndOfStream(IJsonReader reader, string context = null)
		{
			var message = context != null
				? string.Format("Unexpected end of stream while {0} at path '{1}'. The stream may be incomplete, closed prematurely, or in an invalid format.", context, reader.Context.GetPath())
				: string.Format("Unexpected end of stream while more data was expected at path '{0}'. This can happen if you forgot to rewind the stream, if the network stream is incomplete, or if the document is missing closing characters.", reader.Context.GetPath());
			return new JsonSerializationException(message, ErrorCode.UnexpectedEndOfStream, reader);
		}
		public static Exception UnexpectedMemberName(string memberName, string expected, IJsonReader reader)
		{
			return new JsonSerializationException
			(
				string.Format("Unexpected member '{0}' was read while '{1}' was expected at path '{2}'. Ensure that JSON member names match the target object's property names (case-sensitive) or use [DataMember(Name=...)] attribute.", memberName, expected, reader.Context.GetPath()),
				ErrorCode.UnexpectedMemberName,
				reader
			);
		}
		public static Exception UnexpectedToken(IJsonReader reader, params JsonToken[] expectedTokens)
		{
			return UnexpectedToken(reader, null, expectedTokens);
		}
		public static Exception UnexpectedToken(IJsonReader reader, Type expectedType, params JsonToken[] expectedTokens)
		{
			var tokensStr = default(string);
			if (expectedTokens == null || expectedTokens.Length == 0)
			{
				tokensStr = "<no tokens>";
			}
			else
			{
				var tokens = expectedTokens.Select(c =>
				{
					switch (c)
					{
						case JsonToken.BeginArray: return "[";
						case JsonToken.EndOfArray: return "]";
						case JsonToken.BeginObject: return "{";
						case JsonToken.EndOfObject: return "}";
						case JsonToken.Member: return "member name";
						case JsonToken.None:
						case JsonToken.Number:
						case JsonToken.StringLiteral:
						case JsonToken.DateTime:
						case JsonToken.Null:
						case JsonToken.Boolean:
						case JsonToken.EndOfStream:
						default: return c.ToString();
					}
				}).ToArray();
				tokensStr = string.Join(", ", tokens);
			}

			if (reader.Token == JsonToken.EndOfStream)
			{
				return UnexpectedEndOfStream(reader);
			}

			var typeInfo = expectedType != null ? string.Format(" for type '{0}'", expectedType.Name) : "";
			var advice = "";
			if (reader.Token == JsonToken.BeginObject && expectedTokens != null && expectedTokens.Contains(JsonToken.BeginArray))
				advice = " Found '{' instead of expected '['. Ensure input data is a collection.";
			else if (reader.Token == JsonToken.BeginArray && expectedTokens != null && expectedTokens.Contains(JsonToken.BeginObject))
				advice = " Found '[' instead of expected '{'. Ensure input data is a single object.";
			else if (reader.Token == JsonToken.Member && expectedTokens != null && (expectedTokens.Contains(JsonToken.StringLiteral) || expectedTokens.Contains(JsonToken.Number)))
				advice = " Found a member name but expected a value. Check for misplaced colons or incorrect nesting.";

			var message = expectedTokens != null && expectedTokens.Length > 1
				? string.Format("Unexpected token '{0}' was read while any of '{1}' were expected{2} at path '{3}'.{4}", reader.Token, tokensStr, typeInfo, reader.Context.GetPath(), advice)
				: string.Format("Unexpected token '{0}' was read while '{1}' was expected{2} at path '{3}'.{4}", reader.Token, tokensStr, typeInfo, reader.Context.GetPath(), advice);

			return new JsonSerializationException(message, ErrorCode.UnexpectedToken, reader);
		}
		public static Exception UnknownEscapeSequence(string escape, IJsonReader reader)
		{
			return new JsonSerializationException
			(
				string.Format("An unknown escape sequence '{0}' was encountered at path '{1}'. This typically indicates an invalid or non-standard JSON escape sequence. Ensure the JSON follows RFC 8259 standards for string escaping.", escape, reader.Context.GetPath()),
				ErrorCode.UnknownEscapeSequence,
				reader
			);
		}
