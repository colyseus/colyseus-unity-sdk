	[Serializable]
	public class JsonSerializationException : SerializationException
	{
		public enum ErrorCode
		{
			SerializationException = 1,
			EmptyMemberName,
			DiscriminatorNotFirstMemberOfObject,
			CantCreateInstanceOfType,
			SerializationGraphIsTooBig,
			SerializationGraphIsTooDeep,
			TypeIsNotValid,
			SerializingUnknownType,
			SerializingSpecialSystemType,
			UnexpectedEndOfStream,
			UnexpectedMemberName,
			UnexpectedToken,
			UnknownEscapeSequence,
			UnknownDiscriminatorValue,
			SerializationFramesCorruption,
			StreamIsNotReadable,
			StreamIsNotWriteable,
			UnterminatedStringLiteral,
			UnknownNotation,
			MemberNameIsNotSpecified,
			TypeRequiresCustomSerializer,
			CircularReferenceDetected,
			FailedToReadDictionaryKey,
			FailedToReadDictionaryValue,
			UnsupportedMemberType,
			CantSerializeDelegateType,
			MemberIsWriteOnly,
			MemberIsReadOnly,
			FailedToResolveMemberType,
			FailedToReadMemberValue,
			FailedToSetMemberValue,
			FailedToParseDateTime
		}

		public ErrorCode Code { get; set; }
		public int LineNumber { get; set; }
		public int ColumnNumber { get; set; }
		public ulong CharactersWritten { get; set; }

		internal JsonSerializationException(string message, ErrorCode errorCode, IJsonReader reader = null)
			: base(message)
		{
			this.Code = errorCode;
			if (reader != null)
				this.Update(reader);
		}
		internal JsonSerializationException(string message, ErrorCode errorCode, IJsonReader reader, Exception innerException)
			: base(message, innerException)
		{
			this.Code = errorCode;
			if (reader != null)
				this.Update(reader);
		}
		internal JsonSerializationException(string message, Exception innerException)
			: base(message, innerException)
		{
			this.Code = ErrorCode.SerializationException;
		}

		protected JsonSerializationException(SerializationInfo info, StreamingContext context)
			: base(info, context)
		{
			this.Code = (ErrorCode)info.GetInt32("Code");
			this.LineNumber = info.GetInt32("LineNumber");
			this.ColumnNumber = info.GetInt32("ColumnNumber");
			this.CharactersWritten = info.GetUInt64("CharactersWritten");
		}

		private void Update(IJsonReader reader)
		{
			this.LineNumber = reader.Value.LineNumber;
			this.ColumnNumber = reader.Value.ColumnNumber;
			//this.Path = reader.Value.Path;
		}

		[SecurityCritical]
		public override void GetObjectData(SerializationInfo info, StreamingContext context)
		{
			info.AddValue("Code", (int)this.Code);
			info.AddValue("LineNumber", this.LineNumber);
			info.AddValue("ColumnNumber", this.ColumnNumber);
			info.AddValue("CharactersWritten", this.CharactersWritten);

			base.GetObjectData(info, context);
		}

		public static Exception MemberNameIsEmpty(IJsonReader reader)
		{
			return new JsonSerializationException
			(
				string.Format("An empty member name was deserialized at path '{0}'. This can occur when the input JSON contains an empty key or if there is an error in a custom serializer. Ensure all object keys are non-empty strings.", reader.Context.GetPath()),
				ErrorCode.EmptyMemberName,
				reader
			);
		}
		public static Exception MemberNameIsNotSet()
		{
			return new JsonSerializationException
			(
				"A member name is not set before writing a value to an object. This usually indicates that a custom 'TypeSerializer' implementation is missing a 'WriteMember()' call before writing a property value.",
				ErrorCode.MemberNameIsNotSpecified
			);
		}
		public static Exception DiscriminatorIsNotFirstMember(IJsonReader reader)
		{
			return new JsonSerializationException
			(
				string.Format("The type discriminator member '{0}' must be the first member of the object at path '{1}'. This often happens when the JSON was generated by a tool that does not preserve property order or when the discriminator was added manually. Ensure the '$type' or '_type' property appears first.", ObjectSerializer.TYPE_MEMBER_NAME, reader.Context.GetPath()),
				ErrorCode.DiscriminatorNotFirstMemberOfObject,
				reader
			);
		}
		public static Exception CantCreateInstanceOfType(Type type)
		{
			var constructors = type.GetConstructors(BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance);
			var allConstructors = "<empty>";
			if (constructors.Length > 0)
			{
				allConstructors = string.Join("\r\n", constructors.Select(ctr => ctr.ToString()).ToArray());
			}

			return new JsonSerializationException
			(
				string.Format("Unable to deserialize instance of '{0}' because ", type.FullName) +
					(type.GetTypeInfo().IsAbstract ? "it is an abstract type." : "no parameter-less constructor is defined for the type. All constructors: \r\n\t" + allConstructors),
				ErrorCode.CantCreateInstanceOfType
			);
		}
		public static Exception SerializationGraphIsTooBig(IJsonReader reader, ulong maxObjects)
		{
			return new JsonSerializationException
			(
				string.Format("The serialization graph exceeds the maximum allowed number of objects ({0}) at path '{1}'. This might be caused by extremely large data structures or an infinite loop in object references. Consider increasing 'SerializationContext.MaxObjects' if this is intentional.", maxObjects, reader.Context.GetPath()),
				ErrorCode.SerializationGraphIsTooBig
			);
		}
		public static Exception SerializationGraphIsTooDeep(IJsonReader reader, ulong maxDepth)
		{
			return new JsonSerializationException
			(
					string.Format("The serialization graph exceeds the maximum allowed depth ({0}) at path '{1}'. This often points to circular object references or very deep nesting. Consider increasing 'SerializationContext.MaxDepth' if this is intentional, or check for recursive references.", maxDepth, reader.Context.GetPath()),
				ErrorCode.SerializationGraphIsTooDeep)
			;
		}
		public static Exception SerializationGraphIsTooDeep(IJsonWriter writer, ulong maxDepth)
		{
			return new JsonSerializationException
			(
					string.Format("The serialization graph exceeds the maximum allowed depth ({0}) at path '{1}'. This often points to circular object references or very deep nesting. Consider increasing 'SerializationContext.MaxDepth' if this is intentional, or check for recursive references.", maxDepth, writer.Context.GetPath()),
				ErrorCode.SerializationGraphIsTooDeep)
			;
		}
		public static Exception CircularReferenceDetected(IJsonWriter writer, Type type)
		{
			return new JsonSerializationException
			(
				string.Format("A circular reference was detected while serializing an instance of type '{0}' at path '{1}'. This library does not support cyclic object graphs; break the cycle or exclude the back-reference member with an '[IgnoreDataMember]' attribute.", type.FullName, writer.Context.GetPath()),
				ErrorCode.CircularReferenceDetected
			);
		}
